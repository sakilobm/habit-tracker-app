const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('@expo/config-plugins');

const MIPMAP_DIRS = [
  'mipmap-anydpi-v26',
  'mipmap-hdpi',
  'mipmap-mdpi',
  'mipmap-xhdpi',
  'mipmap-xxhdpi',
  'mipmap-xxxhdpi',
];

const WEBP_CONFLICTS = [
  'ic_launcher.webp',
  'ic_launcher_foreground.webp',
  'ic_launcher_round.webp',
];

/**
 * Expo Config Plugin: withCustomAndroidIcons
 * Copies pre-generated Android launcher icons and adaptive background color
 * from `assets/habit-tracker-resulation/android` into `android/app/src/main/res`,
 * removing conflicting `.webp` launcher files generated by default prebuild.
 *
 * @param {import('@expo/config-types').ExpoConfig} config
 * @returns {import('@expo/config-types').ExpoConfig}
 */
module.exports = function withCustomAndroidIcons(config) {
  return withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const projectRoot = modConfig.modRequest.projectRoot;
      const sourceRoot = path.join(projectRoot, 'assets', 'habit-tracker-resulation', 'android');
      const resRoot = path.join(modConfig.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res');

      if (!fs.existsSync(sourceRoot)) {
        console.warn(`[withCustomAndroidIcons] Source folder not found: ${sourceRoot}`);
        return modConfig;
      }

      for (const dir of MIPMAP_DIRS) {
        const srcDir = path.join(sourceRoot, dir);
        const destDir = path.join(resRoot, dir);
        if (!fs.existsSync(srcDir)) continue;

        fs.mkdirSync(destDir, { recursive: true });

        // Remove Expo's default .webp files to prevent duplicate resource errors with .png
        for (const webpName of WEBP_CONFLICTS) {
          const webpPath = path.join(destDir, webpName);
          if (fs.existsSync(webpPath)) {
            fs.unlinkSync(webpPath);
          }
        }

        for (const file of fs.readdirSync(srcDir)) {
          fs.copyFileSync(path.join(srcDir, file), path.join(destDir, file));
        }
      }

      // Copy values/ic_launcher_background.xml
      const srcBgXml = path.join(sourceRoot, 'values', 'ic_launcher_background.xml');
      if (fs.existsSync(srcBgXml)) {
        const destValuesDir = path.join(resRoot, 'values');
        fs.mkdirSync(destValuesDir, { recursive: true });
        fs.copyFileSync(srcBgXml, path.join(destValuesDir, 'ic_launcher_background.xml'));
      }

      return modConfig;
    },
  ]);
};

